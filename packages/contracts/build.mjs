#!/usr/bin/env node
/**
 * Bundles every contract in src/ into contracts.json, the one file the documentation is generated
 * from. Never edit contracts.json; edit a contract in src/ and build.
 *
 *   node packages/contracts/build.mjs          write it
 *   node packages/contracts/build.mjs --check  fail if it is out of date
 */

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const order = { primitive: 0, cell: 1, surface: 2 };
const contracts = readdirSync(join(here, 'src'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => {
    const { $schema, ...c } = JSON.parse(readFileSync(join(here, 'src', f), 'utf8'));
    return c;
  })
  .sort((a, b) => order[a.layer] - order[b.layer] || a.name.localeCompare(b.name));

const out = JSON.stringify({ about: 'Generated by packages/contracts/build.mjs from src/*.json; do not edit.', contracts }, null, 2) + '\n';
const file = join(here, 'contracts.json');

if (process.argv.includes('--check')) {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== out) {
    console.error('✖ contracts.json is out of date: run node packages/contracts/build.mjs');
    process.exit(1);
  }
  console.log('✔ contracts.json is up to date');
} else {
  writeFileSync(file, out);
  console.log(`✔ ${contracts.length} contracts written to contracts.json`);
}
