#!/usr/bin/env node
/**
 * Emit Primal's tokens from src/tokens.mjs:
 *   primal-tokens.css   CSS custom properties, light and dark, reduced motion
 *   primal-tokens.json  every token with its value(s) and meaning
 *
 *   node packages/tokens/build.mjs           write both files
 *   node packages/tokens/build.mjs --check   exit 1 if either file is out of date
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as t from './src/tokens.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const v = (name) => `--${t.PREFIX}-${name}`;
const oklch = t.css;

/** A step that grows linearly from 320px to 1440px wide. */
function fluid([min, max]) {
  if (min === max) return `${min / 16}rem`;
  const slope = (max - min) / (1440 - 320);
  const intercept = (min - slope * 320) / 16;
  return `clamp(${min / 16}rem, ${+intercept.toFixed(4)}rem + ${+(slope * 100).toFixed(4)}vw, ${max / 16}rem)`;
}

const decl = (name, value, meaning) => `  /* ${meaning} */\n  ${v(name)}: ${value};`;

const root = [];
const json = {};
const add = (group, name, value, meaning, extra = {}) => {
  json[v(name)] = { group, value, meaning, ...extra };
  root.push(decl(name, value, meaning));
};

for (const [name, input] of Object.entries(t.INPUTS)) add('choice', name, oklch(input.value), input.meaning);
const scheme = t.SCHEMES[t.DEFAULT_SCHEME];
add('choice', 'companion-angle', `${scheme.companion}`, `How far round the wheel the companion sits from the primary (${scheme.label} by default).`);
add('choice', 'tertiary-angle', `${scheme.tertiary}`, `How far round the wheel the tertiary sits from the primary (${scheme.label} by default).`);
add('choice', 'companion-lightness', '0', 'How much lighter (positive) or darker (negative) the companion is than the primary.');
add('choice', 'tertiary-lightness', '0', 'How much lighter (positive) or darker (negative) the tertiary is than the primary.');
const light = t.palette(t.DEFAULTS, 'light');
const dark = t.palette(t.DEFAULTS, 'dark');
const roles = [];
for (const [name, role] of Object.entries(t.ROLES)) {
  const group = name in t.SYSTEM || name.endsWith('-surface') && name.replace('-surface', '') in t.SYSTEM ? 'system' : 'colour';
  json[v(`color-${name}`)] = { group, value: role.css, meaning: role.meaning, light: oklch(light[name]), dark: oklch(dark[name]) };
  roles.push(decl(`color-${name}`, role.css, role.meaning));
}
const steps = t.scale(t.DEFAULTS);
for (const step of Object.keys(t.SCALE)) {
  const [toward, share] = t.SCALE[step] ?? [];
  const meaning = toward ? `Step ${step}: ${share}% primary, the rest the project's ${toward}.` : 'Step 500: the primary as chosen.';
  json[v(`primary-${step}`)] = { group: 'scale', value: t.scaleCss(step), meaning, light: oklch(steps[step]), dark: oklch(steps[step]) };
  roles.push(decl(`primary-${step}`, t.scaleCss(step), meaning));
}
for (const [name, f] of Object.entries(t.type.family)) add('type', `font-${name}`, f.value, f.meaning);
for (const [name, s] of Object.entries(t.type.size)) add('type', `text-${name}`, fluid(s.px), s.meaning, { px: s.px });
for (const [name, l] of Object.entries(t.type.leading)) add('type', `leading-${name}`, l.value, l.meaning);
for (const [name, w] of Object.entries(t.type.weight)) add('type', `weight-${name}`, w.value, w.meaning);
add('type', 'measure', t.type.measure.value, t.type.measure.meaning);
for (const [name, s] of Object.entries(t.space)) add('space', name, s.value, s.meaning);
for (const [name, l] of Object.entries(t.layout)) add('layout', name, l.value, l.meaning);
for (const [name, s] of Object.entries(t.shape)) add('shape', name, s.value, s.meaning);
for (const [name, e] of Object.entries(t.elevation)) add('elevation', `elevation-${name}`, e.value, e.meaning);
for (const [name, l] of Object.entries(t.layer)) add('layer', `layer-${name}`, l.value, l.meaning);
for (const [name, m] of Object.entries(t.motion)) add('motion', name, m.value, m.meaning);

const still = Object.keys(t.motion)
  .filter((name) => name.startsWith('duration-'))
  .map((name) => `  ${v(name)}: 0ms;`);

const css = `/*
 * Mycelium Primal tokens. Generated by packages/tokens/build.mjs from src/tokens.mjs; do not edit.
 *
 * Re-theme Primal by overriding these custom properties in your own file, loaded after this one.
 * For colour, override only the choices: --pr-black, --pr-white, --pr-primary and the two
 * harmony angles. Every colour role, the primary's states and its 50–950 scale derive from them.
 * Primal's own choices are Mycelium's: Magma #E61924 on ink #0B0B0D and white #FFFFFF.
 *
 * Light and dark follow the system; data-theme="light" or "dark" forces one on any element.
 */

:root {
  color-scheme: light dark;

${root.join('\n\n')}
}

/*
 * The colour roles and the primary's scale, derived from the choices above. Declared again on [data-palette], so a region
 * that sets its own --pr-black, --pr-white or --pr-primary gets its own derived roles.
 */
:root,
[data-palette] {
${roles.join('\n\n')}
}

[data-theme='light'] {
  color-scheme: light;
}

[data-theme='dark'] {
  color-scheme: dark;
}

@media (prefers-reduced-motion: reduce) {
  :root {
${still.map((l) => `  ${l}`).join('\n')}
  }
}
`;

const out = {
  css: [join(here, 'primal-tokens.css'), css],
  json: [join(here, 'primal-tokens.json'), `${JSON.stringify(json, null, 2)}\n`],
};

if (process.argv.includes('--check')) {
  const stale = Object.values(out).filter(([path, text]) => {
    try {
      return readFileSync(path, 'utf8') !== text;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`✖ out of date: ${stale.map(([p]) => p).join(', ')}. Run node packages/tokens/build.mjs`);
    process.exit(1);
  }
  console.log('✔ tokens are up to date');
} else {
  for (const [path, text] of Object.values(out)) writeFileSync(path, text);
  console.log(`✔ ${Object.keys(json).length} tokens written`);
}
